"""Silkscreen the function of every connector pin, per connectors.md.

    python3 tools/pin_labels.py              # report placement and collisions
    python3 tools/pin_labels.py --apply
    python3 tools/pin_labels.py --strip --apply     # remove them again
    python3 tools/pin_labels.py --lock --apply      # protect them from re-runs
    python3 tools/pin_labels.py --relock --apply    # regenerate even locked ones

WHY
---
connectors.md: "This board is assembled once and cabled differently for each
instrument, by hand, months apart. The loom is where the mistakes will be, not
the PCB. So print the function of every pin beside every connector."

WHAT DECIDES THE DESIGN
-----------------------
Pin pitch, and nothing else. At 2.50 mm pitch with 0.25 mm silk clearance, one
row of 1 mm text fits TWO characters -- not enough for "3V3", let alone
"PGOOD". Staggering alternate pins into two rows doubles the effective pitch to
5.00 mm and buys five characters, which covers every label here except MIC_RTN
(shortened to RTN).

So labels stagger into as many rows as the pitch demands:

    rows = ceil((label width + clearance) / pitch)

Most connectors need 2. J13A is JST-SH at 1.00 mm pitch and needs 3.

Connectors whose pins run in a LINE ACROSS the label direction do not stagger
at all -- a 1 mm line of text is 1.06 mm tall against a 2.50 mm pitch, so the
labels simply stack. That covers J1, J3, J4, J17, J18, J14 and the two columns
of J11.

MEASURE SILK, NOT COURTYARDS
----------------------------
Courtyard-to-courtyard says J1, J3, J4 and J13A have 0.94-1.51 mm and cannot be
labelled. That is the wrong measurement: a courtyard is a placement keepout, it
does not reserve silkscreen. Measured silk-to-silk, every connector on the
board has room -- those four on their OUTWARD side, toward the board edge,
where they have 3.8-4.2 mm.

BOARD-LEVEL TEXT, DELIBERATELY
------------------------------
The labels are gr_text on the board, not fp_text inside each footprint, so they
do NOT follow a connector that gets moved. That is the trade, and it is the
same one cycle.py makes with routing: the labels are a disposable rendering of
placement, regenerated by re-running this. Every object carries a uuid5 derived
from "caryatid-pinlabel-<ref>-<pin>", so --strip removes exactly what this tool
wrote and nothing a human placed.

MOVE A CONNECTOR AND THE LABELS DO NOT FOLLOW. Re-run this after any placement
change, and check the collision report rather than assuming.

LOCK ANYTHING YOU ADJUST BY HAND. A hand-moved label keeps the uuid this tool
gave it, so without a lock the next --apply silently reverts it to the computed
position -- the same trap the board already documents for copper. --lock marks
every label this tool owns; strip() then refuses to touch them and treats them
as obstacles instead, and --relock is the deliberate override.
"""
